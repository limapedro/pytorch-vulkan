"""Generate docs/PARITY.md from parity/manifest.yaml.

No argparse by project convention; edit Config defaults or call from Python.
"""

from dataclasses import dataclass
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent


@dataclass(frozen=True)
class Config:
    manifest: Path = ROOT / "parity" / "manifest.yaml"
    output: Path = ROOT / "docs" / "PARITY.md"
    statuses: tuple[str, ...] = (
        "roadmap",
        "in progress",
        "forward done",
        "forward+backward done",
        "optimized",
    )


def cell(value: object) -> str:
    if value is None:
        return "-"
    if isinstance(value, (list, tuple)):
        return ", ".join(str(v) for v in value) or "-"
    return str(value)


def render(data: dict, cfg: Config) -> str:
    lines = [
        "# PARITY",
        "",
        "<!-- Generated by tools/generate_parity_doc.py from parity/manifest.yaml. Do not edit by hand. -->",
        "",
        "Status legend: " + " / ".join(cfg.statuses) + ".",
        "",
        "Everything here is generated from a machine-readable manifest so the table cannot",
        "rot. A blank parity result means **not measured**, never 'pass'.",
        "",
    ]
    ops = data["ops"]
    counts = {s: sum(op["status"] == s for op in ops) for s in cfg.statuses}
    lines.append("Summary (ops): " + ", ".join(f"{s}={n}" for s, n in counts.items()) + ".")
    lines += [
        "",
        "## Ops",
        "",
        "| ATen op | Overloads | Tier | Dtypes | Status | Parity result / tolerance | Perf vs CUDA | PR |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for op in ops:
        lines.append(
            "| {name} | {overloads} | {tier} | {dtypes} | {status} | {parity} | {perf} | {pr} |".format(
                name=cell(op["name"]),
                overloads=cell(op.get("overloads")),
                tier=cell(op.get("tier")),
                dtypes=cell(op.get("dtypes")),
                status=cell(op.get("status")),
                parity=cell(op.get("parity")),
                perf=cell(op.get("perf_ratio_cuda")),
                pr=cell(op.get("pr")),
            )
        )
    layers = data.get("layers", [])
    lcounts = {s: sum(layer["status"] == s for layer in layers) for s in cfg.statuses}
    lines += [
        "",
        "Summary (layers): " + ", ".join(f"{s}={n}" for s, n in lcounts.items()) + ".",
        "",
        "## Models",
        "",
        "| Model | Status | CPU fallback count | Parity | Perf vs CUDA | PR |",
        "|---|---|---|---|---|---|",
    ]
    for layer in layers:
        lines.append(
            "| {name} | {status} | {fallback} | {parity} | {perf} | {pr} |".format(
                name=cell(layer["name"]),
                status=cell(layer.get("status")),
                fallback=cell(layer.get("fallback_count")),
                parity=cell(layer.get("parity")),
                perf=cell(layer.get("perf_ratio_cuda")),
                pr=cell(layer.get("pr")),
            )
        )
    lines.append("")
    return "\n".join(lines)


def main(cfg: Config | None = None) -> None:
    cfg = cfg or Config()
    data = yaml.safe_load(cfg.manifest.read_text(encoding="utf-8"))
    cfg.output.write_text(render(data, cfg), encoding="utf-8")


if __name__ == "__main__":
    main()
